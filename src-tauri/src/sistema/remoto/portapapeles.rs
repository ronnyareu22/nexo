//! Portapapeles liviano y su historial (Mac).
//!
//! - Mira el contador de cambios de NSPasteboard: cada 150 ms durante una sesión de RustDesk y cada 2 s sin ella.
//!   Mirar es barato; leer y achicar solo pasa cuando algo cambió, y siempre en este hilo aparte.
//! - Durante la sesión, si se copia una imagen grande (más de 1600 px de lado o 1,5 MB), la cambia enseguida por
//!   una copia en PNG de 1600 px como mucho (1x), marcada con `com.ronny.nexo.reducida` para no tocarla de nuevo.
//!   Así RustDesk manda una imagen liviana y no se congela. Los archivos copiados en Finder no se tocan.
//! - Guarda las últimas 12 copias (texto e imágenes) mientras Nexo corre. Las imágenes van a la carpeta de la app
//!   (`portapapeles/`, unos 20 MB como mucho; se borran las más viejas primero). No guarda lo que parece una
//!   contraseña (los gestores de contraseñas lo marcan como oculto o pasajero).

use super::{EntradaPortapapeles, imagen};
use objc2::msg_send;
use objc2::rc::{Retained, autoreleasepool};
use objc2::runtime::{AnyClass, AnyObject};
use objc2_foundation::{NSArray, NSData, NSString};
use std::path::PathBuf;
use std::sync::atomic::{AtomicU64, Ordering};
use std::sync::{Mutex, OnceLock};
use std::time::{Duration, SystemTime, UNIX_EPOCH};
use tauri::{AppHandle, Emitter, Manager};

/// Marca de las imágenes que ya dejó livianas Nexo (achicadas o capturadas).
const MARCA_REDUCIDA: &str = "com.ronny.nexo.reducida";
/// Marca de lo que Nexo vuelve a copiar desde el historial (ya está en la lista).
const MARCA_HISTORIAL: &str = "com.ronny.nexo.historial";
const TEXTO_PLANO: &str = "public.utf8-plain-text";

const LADO_MAX: u32 = 1600;
const PESO_MAX: usize = 1_500_000;
const MAX_ENTRADAS: usize = 12;
const MAX_DISCO: u64 = 20 * 1024 * 1024;
/// Textos más largos no se guardan (no tiene sentido volver a copiar un registro enorme a medias).
const MAX_TEXTO: usize = 20_000;
/// Lo que se manda a la interfaz de cada texto.
const VISTA_TEXTO: usize = 2000;
const LADO_MINIATURA: u32 = 160;

/// Imágenes que se miran, en orden de preferencia. GIF no: se perdería la animación.
const TIPOS_IMAGEN: [&str; 4] = ["public.png", "public.tiff", "public.jpeg", "public.heic"];

/// Texto con formato: si viene, lo copiado es texto aunque también traiga una imagen.
const TIPOS_CON_FORMATO: [&str; 3] = ["public.rtf", "public.rtfd", "com.apple.flat-rtfd"];

/// Marcas de los gestores de contraseñas y de contenido pasajero (nspasteboard.org y otros).
const TIPOS_SECRETOS: [&str; 7] = [
    "org.nspasteboard.ConcealedType",
    "org.nspasteboard.TransientType",
    "org.nspasteboard.AutoGeneratedType",
    "com.agilebits.onepassword",
    "de.petermaurer.TransientPasteboardType",
    "com.typeit4me.clipping",
    "Pasteboard generator type",
];

enum Contenido {
    Texto(String),
    Imagen { archivo: PathBuf, miniatura: String, ancho: u32, alto: u32, huella: u64, peso: u64 },
}

struct Entrada {
    id: u64,
    contenido: Contenido,
    momento: u64,
    origen: &'static str,
}

static HISTORIAL: Mutex<Vec<Entrada>> = Mutex::new(Vec::new());
static SIGUIENTE_ID: AtomicU64 = AtomicU64::new(1);
static CARPETA: OnceLock<PathBuf> = OnceLock::new();

pub fn iniciar(app: AppHandle) {
    if let Ok(dir) = app.path().app_config_dir() {
        let carpeta = dir.join("portapapeles");
        // El historial vive mientras Nexo corre: lo de la vez anterior se borra.
        let _ = std::fs::remove_dir_all(&carpeta);
        let _ = CARPETA.set(carpeta);
    }
    if let Err(e) = std::thread::Builder::new().name("nexo-portapapeles".into()).spawn(move || vigilar(app)) {
        eprintln!("Nexo: no se pudo vigilar el portapapeles ({e})");
    }
}

fn vigilar(app: AppHandle) {
    let mut ultima = cuenta().unwrap_or(0);
    loop {
        let en_sesion = super::mac::SESION_ACTIVA.load(Ordering::Relaxed);
        std::thread::sleep(if en_sesion { Duration::from_millis(150) } else { Duration::from_secs(2) });
        let Some(c) = cuenta() else { continue };
        if c == ultima {
            continue;
        }
        ultima = c;
        let en_sesion = super::mac::SESION_ACTIVA.load(Ordering::Relaxed);
        if let Some(propia) = procesar(&app, c, en_sesion) {
            ultima = propia; // lo que escribió Nexo no se vuelve a mirar
        }
    }
}

// ---------------------------------------------------------------- NSPasteboard

/// Llama `f` con el portapapeles general, dentro de su propio autoreleasepool.
fn con_portapapeles<R>(f: impl FnOnce(&AnyObject) -> Option<R>) -> Option<R> {
    let clase = AnyClass::get(c"NSPasteboard")?;
    autoreleasepool(|_| {
        // SAFETY: generalPasteboard devuelve el portapapeles compartido, que vive toda la sesión.
        let pb: *mut AnyObject = unsafe { msg_send![clase, generalPasteboard] };
        let pb = unsafe { pb.as_ref() }?;
        f(pb)
    })
}

fn cuenta() -> Option<isize> {
    // SAFETY: changeCount es un NSInteger.
    con_portapapeles(|pb| Some(unsafe { msg_send![pb, changeCount] }))
}

fn tipos() -> Vec<String> {
    con_portapapeles(|pb| {
        // SAFETY: types es un NSArray<NSString> (o nil).
        let lista: Option<Retained<NSArray<NSString>>> = unsafe { msg_send![pb, types] };
        Some(lista.map(|l| l.iter().map(|t| t.to_string()).collect()).unwrap_or_default())
    })
    .unwrap_or_default()
}

fn datos(tipo: &str) -> Option<Vec<u8>> {
    con_portapapeles(|pb| {
        let t = NSString::from_str(tipo);
        // SAFETY: dataForType: devuelve NSData o nil.
        let d: Option<Retained<NSData>> = unsafe { msg_send![pb, dataForType: &*t] };
        d.map(|d| d.to_vec())
    })
}

fn texto() -> Option<String> {
    con_portapapeles(|pb| {
        let t = NSString::from_str(TEXTO_PLANO);
        // SAFETY: stringForType: devuelve NSString o nil.
        let s: Option<Retained<NSString>> = unsafe { msg_send![pb, stringForType: &*t] };
        s.map(|s| s.to_string())
    })
}

/// Reemplaza todo el portapapeles por estos tipos y datos. Devuelve el contador nuevo.
fn escribir(items: &[(&str, &[u8])]) -> Option<isize> {
    con_portapapeles(|pb| {
        let tipos: Vec<Retained<NSString>> = items.iter().map(|(t, _)| NSString::from_str(t)).collect();
        let lista = NSArray::from_retained_slice(&tipos);
        let nadie: *mut AnyObject = std::ptr::null_mut();
        // SAFETY: declareTypes:owner: recibe un NSArray de tipos y un dueño opcional; setData:forType: un NSData.
        unsafe {
            let _: isize = msg_send![pb, declareTypes: &*lista, owner: nadie];
            for ((_, bytes), tipo) in items.iter().zip(&tipos) {
                let d = NSData::with_bytes(bytes);
                let _: bool = msg_send![pb, setData: &*d, forType: &**tipo];
            }
            let c: isize = msg_send![pb, changeCount];
            Some(c)
        }
    })
}

/// Pone un PNG liviano en el portapapeles (lo usa la captura). Si ya pasó por Nexo, no se vuelve a achicar.
pub fn escribir_imagen(png: &[u8]) -> bool {
    escribir(&[("public.png", png), (MARCA_REDUCIDA, b"1".as_slice())]).is_some()
}

// ---------------------------------------------------------------- Cada cambio

/// Mira lo que se acaba de copiar: achica la imagen si hace falta y lo anota en el historial.
/// Devuelve el contador nuevo si Nexo escribió en el portapapeles.
fn procesar(app: &AppHandle, cuenta_leida: isize, en_sesion: bool) -> Option<isize> {
    let tipos = tipos();
    let tiene = |t: &str| tipos.iter().any(|x| x == t);
    if tipos.is_empty() || tiene(MARCA_HISTORIAL) || tipos.iter().any(|t| TIPOS_SECRETOS.contains(&t.as_str())) {
        return None;
    }
    // Archivos copiados en Finder: se pegan como archivos; cambiarlos rompería eso.
    if tiene("public.file-url") {
        return None;
    }
    let de_nexo = tiene(MARCA_REDUCIDA);
    let origen = if de_nexo { "mac" } else { origen(&tipos, en_sesion) };

    // Texto con formato (Word, Pages, Numbers…) trae también una imagen de la selección, pero es texto: no se toca.
    let con_formato = TIPOS_CON_FORMATO.iter().any(|t| tiene(t));
    let tipo_imagen = if con_formato { None } else { TIPOS_IMAGEN.iter().find(|t| tiene(t)) };
    let Some(tipo) = tipo_imagen else {
        if let Some(t) = texto() {
            agregar_texto(app, t, origen);
        }
        return None;
    };
    let original = datos(tipo)?;
    let medida = imagen::medir(&original)?;
    let lado = medida.ancho.max(medida.alto);
    let grande = lado > LADO_MAX || original.len() > PESO_MAX;

    let mut escrita = None;
    let mut liviana: Option<(Vec<u8>, u32, u32)> = None;
    if en_sesion && grande && !de_nexo && super::LIVIANO.load(Ordering::Relaxed) {
        // 1x (las capturas Retina dicen 144 ppp) y 1600 px como mucho.
        let escala = (medida.dpi / 72.0).max(1.0);
        let objetivo = ((lado as f64 / escala).round() as u32).clamp(1, LADO_MAX);
        if let Some((png, ancho, alto)) = imagen::achicar_png(&original, objetivo) {
            // Solo si sirve y si nadie copió otra cosa mientras tanto. El texto que venía con la imagen se conserva.
            if (ancho.max(alto) < lado || png.len() < original.len()) && cuenta() == Some(cuenta_leida) {
                let texto_plano = datos(TEXTO_PLANO);
                let mut items: Vec<(&str, &[u8])> = vec![("public.png", png.as_slice()), (MARCA_REDUCIDA, b"1".as_slice())];
                if let Some(t) = &texto_plano {
                    items.push((TEXTO_PLANO, t.as_slice()));
                }
                escrita = escribir(&items);
            }
            liviana = Some((png, ancho, alto));
        }
    }

    // Al historial va una copia de 1600 px como mucho, en PNG.
    let para_historial = match liviana {
        Some(l) => Some(l),
        None if lado > LADO_MAX || *tipo != "public.png" => imagen::achicar_png(&original, LADO_MAX),
        None => Some((original, medida.ancho, medida.alto)),
    };
    if let Some((png, ancho, alto)) = para_historial {
        agregar_imagen(app, png, ancho, alto, origen);
    }
    escrita
}

/// De dónde vino lo copiado (estimación). Sin sesión, de la Mac. En sesión: si lo marcó RustDesk o RustDesk está
/// al frente, del PC; si se acaba de pulsar copiar en la Mac (⌘C, o Ctrl+C traducido), de la Mac; si no, del PC
/// (RustDesk lo trajo solo).
fn origen(tipos: &[String], en_sesion: bool) -> &'static str {
    if !en_sesion {
        return "mac";
    }
    let de_rustdesk = |t: &str| t.to_ascii_lowercase().contains("rustdesk");
    if tipos.iter().any(|t| de_rustdesk(t)) || super::mac::app_al_frente().is_some_and(|id| de_rustdesk(&id)) {
        return "remoto";
    }
    if super::teclado::copia_reciente(2000) { "mac" } else { "remoto" }
}

// ---------------------------------------------------------------- Historial

fn ahora() -> u64 {
    SystemTime::now().duration_since(UNIX_EPOCH).map(|d| d.as_secs()).unwrap_or(0)
}

fn avisar(app: &AppHandle) {
    let _ = app.emit("portapapeles-cambio", ());
}

fn bloquear() -> std::sync::MutexGuard<'static, Vec<Entrada>> {
    HISTORIAL.lock().unwrap_or_else(|e| e.into_inner())
}

/// Sube una entrada al principio (se volvió a copiar).
fn subir(h: &mut Vec<Entrada>, i: usize, origen: &'static str) {
    if i < h.len() {
        let mut e = h.remove(i);
        e.momento = ahora();
        e.origen = origen;
        h.insert(0, e);
    }
}

fn borrar_archivo(e: &Entrada) {
    if let Contenido::Imagen { archivo, .. } = &e.contenido {
        let _ = std::fs::remove_file(archivo);
    }
}

/// Deja 12 entradas como mucho y las imágenes en 20 MB (se van las más viejas primero).
fn recortar(h: &mut Vec<Entrada>) {
    while h.len() > MAX_ENTRADAS {
        if let Some(e) = h.pop() {
            borrar_archivo(&e);
        }
    }
    loop {
        let total: u64 = h
            .iter()
            .map(|e| match &e.contenido {
                Contenido::Imagen { peso, .. } => *peso,
                Contenido::Texto(_) => 0,
            })
            .sum();
        if total <= MAX_DISCO {
            break;
        }
        let Some(i) = h.iter().rposition(|e| matches!(e.contenido, Contenido::Imagen { .. })) else { break };
        let e = h.remove(i);
        borrar_archivo(&e);
    }
}

fn agregar_texto(app: &AppHandle, texto: String, origen: &'static str) {
    if texto.trim().is_empty() || texto.chars().count() > MAX_TEXTO {
        return;
    }
    {
        let mut h = bloquear();
        match h.iter().position(|e| matches!(&e.contenido, Contenido::Texto(t) if *t == texto)) {
            Some(i) => subir(&mut h, i, origen),
            None => h.insert(
                0,
                Entrada {
                    id: SIGUIENTE_ID.fetch_add(1, Ordering::Relaxed),
                    contenido: Contenido::Texto(texto),
                    momento: ahora(),
                    origen,
                },
            ),
        }
        recortar(&mut h);
    }
    avisar(app);
}

fn agregar_imagen(app: &AppHandle, png: Vec<u8>, ancho: u32, alto: u32, origen: &'static str) {
    let huella = fnv(&png);
    {
        let mut h = bloquear();
        let igual = |e: &Entrada| matches!(&e.contenido, Contenido::Imagen { huella: x, .. } if *x == huella);
        if let Some(i) = h.iter().position(igual) {
            subir(&mut h, i, origen);
            drop(h);
            avisar(app);
            return;
        }
    }
    let Some(carpeta) = CARPETA.get() else { return };
    let Some((mini, _, _)) = imagen::achicar_png(&png, LADO_MINIATURA) else { return };
    let id = SIGUIENTE_ID.fetch_add(1, Ordering::Relaxed);
    let archivo = carpeta.join(format!("{id}.png"));
    if std::fs::create_dir_all(carpeta).is_err() || std::fs::write(&archivo, &png).is_err() {
        return;
    }
    let contenido = Contenido::Imagen {
        archivo,
        miniatura: format!("data:image/png;base64,{}", base64(&mini)),
        ancho,
        alto,
        huella,
        peso: png.len() as u64,
    };
    {
        let mut h = bloquear();
        h.insert(0, Entrada { id, contenido, momento: ahora(), origen });
        recortar(&mut h);
    }
    avisar(app);
}

/// El historial para la interfaz, de la copia más nueva a la más vieja.
pub fn historial() -> Vec<EntradaPortapapeles> {
    bloquear()
        .iter()
        .map(|e| match &e.contenido {
            Contenido::Texto(t) => EntradaPortapapeles {
                id: e.id,
                tipo: "texto",
                texto: Some(t.chars().take(VISTA_TEXTO).collect()),
                largo: Some(t.chars().count()),
                miniatura: None,
                ancho: None,
                alto: None,
                momento: e.momento,
                origen: e.origen,
            },
            Contenido::Imagen { miniatura, ancho, alto, .. } => EntradaPortapapeles {
                id: e.id,
                tipo: "imagen",
                texto: None,
                largo: None,
                miniatura: Some(miniatura.clone()),
                ancho: Some(*ancho),
                alto: Some(*alto),
                momento: e.momento,
                origen: e.origen,
            },
        })
        .collect()
}

/// Vuelve a poner una copia en el portapapeles y la sube al principio.
pub fn copiar(app: &AppHandle, id: u64) -> Result<(), String> {
    enum Que {
        Texto(String),
        Imagen(PathBuf),
    }
    let que = {
        let h = bloquear();
        let e = h.iter().find(|e| e.id == id).ok_or("Esa copia ya no está en el historial.")?;
        match &e.contenido {
            Contenido::Texto(t) => Que::Texto(t.clone()),
            Contenido::Imagen { archivo, .. } => Que::Imagen(archivo.clone()),
        }
    };
    let marca = b"1".as_slice();
    let escrito = match que {
        Que::Texto(t) => escribir(&[(TEXTO_PLANO, t.as_bytes()), (MARCA_HISTORIAL, marca)]),
        Que::Imagen(archivo) => {
            let png = std::fs::read(archivo).map_err(|_| "No encontré esa imagen. Cópiala de nuevo.")?;
            escribir(&[("public.png", png.as_slice()), (MARCA_REDUCIDA, marca), (MARCA_HISTORIAL, marca)])
        }
    };
    if escrito.is_none() {
        return Err("No pude ponerlo en el portapapeles.".into());
    }
    {
        let mut h = bloquear();
        if let Some(i) = h.iter().position(|e| e.id == id) {
            let origen = h[i].origen;
            subir(&mut h, i, origen);
        }
    }
    avisar(app);
    Ok(())
}

/// Borra todo el historial y sus imágenes.
pub fn borrar(app: &AppHandle) {
    let viejas = std::mem::take(&mut *bloquear());
    for e in &viejas {
        borrar_archivo(e);
    }
    if let Some(carpeta) = CARPETA.get() {
        let _ = std::fs::remove_dir_all(carpeta);
    }
    avisar(app);
}

/// Huella rápida para no repetir la misma imagen (FNV-1a de 64 bits).
fn fnv(datos: &[u8]) -> u64 {
    datos.iter().fold(0xcbf2_9ce4_8422_2325u64, |h, b| (h ^ *b as u64).wrapping_mul(0x0100_0000_01b3))
}

fn base64(datos: &[u8]) -> String {
    const TABLA: &[u8; 64] = b"ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
    let letra = |n: u32| TABLA[(n & 63) as usize] as char;
    let mut s = String::with_capacity(datos.len().div_ceil(3) * 4);
    for trozo in datos.chunks(3) {
        let b0 = trozo.first().copied().unwrap_or(0) as u32;
        let b1 = trozo.get(1).copied().unwrap_or(0) as u32;
        let b2 = trozo.get(2).copied().unwrap_or(0) as u32;
        let n = (b0 << 16) | (b1 << 8) | b2;
        s.push(letra(n >> 18));
        s.push(letra(n >> 12));
        s.push(if trozo.len() > 1 { letra(n >> 6) } else { '=' });
        s.push(if trozo.len() > 2 { letra(n) } else { '=' });
    }
    s
}
